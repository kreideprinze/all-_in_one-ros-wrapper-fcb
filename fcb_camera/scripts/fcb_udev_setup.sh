#!/usr/bin/env bash
# Generate and install udev rules that give the FCB camera stable device names.
#
#   fcb_udev_setup.sh            # detect, print the rules, install with sudo
#   fcb_udev_setup.sh --dry-run  # detect and print only
#
# Plug the camera in first. The video node is found by its V4L2 card name; the
# VISCA port by probing every /dev/ttyACM* and /dev/ttyUSB* with a zoom
# inquiry (the same test the driver uses), then reading its USB IDs.
set -euo pipefail
DRY=0; [[ "${1:-}" == "--dry-run" ]] && DRY=1
HINTS="${FCB_NAME_HINTS:-neohd fcb harrier}"
# Camera boards by USB ID, for when the card name says nothing: the Oppila
# LVDS-USB3 board's is just "FX3 CAMERA". NeoHD: 04b4:00f9 (00f8 on USB 2).
BOARD_IDS="04b4:00f9 04b4:00f8 04b4:0040"
usb_id_of() {  # vvvv:pppp of the USB device behind a /dev node, or nothing
  local p; p=$(udevadm info -q property -n "$1" 2>/dev/null) || return 0
  local v d; v=$(sed -n 's/^ID_VENDOR_ID=//p' <<<"$p"); d=$(sed -n 's/^ID_MODEL_ID=//p' <<<"$p")
  [[ -n "$v" && -n "$d" ]] && echo "$v:$d"
}
on_board() { [[ " $BOARD_IDS " == *" $(usb_id_of "$1") "* ]]; }

video=""
for node in /dev/video*; do
  name=$(cat "/sys/class/video4linux/$(basename "$node")/name" 2>/dev/null | tr 'A-Z' 'a-z' || true)
  idx=$(cat "/sys/class/video4linux/$(basename "$node")/index" 2>/dev/null || echo 0)
  for h in $HINTS; do
    if [[ "$name" == *"$h"* && "$idx" == "0" ]]; then video="$node"; fi
  done
  if [[ -z "$video" && "$idx" == "0" ]] && on_board "$node"; then video="$node"; fi
done
if [[ -n "$video" ]]; then
  echo "video node: $video ($(cat /sys/class/video4linux/$(basename "$video")/name))"
else
  echo "warning: no /dev/video* card name matched '$HINTS' -- is the camera plugged in?" >&2
fi

visca=""
# Camera-board ports first, in interface order (the Oppila board's VISCA port
# is interface 0, its debug port a later one), then everything else.
ports=$( { for p in /dev/ttyACM* /dev/ttyUSB*; do
             [[ -e "$p" ]] || continue
             if on_board "$p"; then
               n=$(udevadm info -q property -n "$p" | sed -n 's/^ID_USB_INTERFACE_NUM=//p')
               echo "0 ${n:-99} $p"
             else
               echo "1 99 $p"
             fi
           done; } | sort -k1,1n -k2,2 | awk '{print $3}')
for port in $ports; do
  if python3 - "$port" <<'PY'
import sys, serial, time
port = sys.argv[1]
# The Oppila board passes replies on only in full 32-byte USB packets, so each
# inquiry is followed by eight broadcast Address Set pads (4-byte answers) to
# push it out; on other boards the pads are answered or ignored, harmlessly.
PADS = bytes([0x88, 0x30, 0x01, 0xFF]) * 8
INQ = bytes([0x81, 0x09, 0x04, 0x47, 0xFF])
def zoom_reply(buf):
    for i in range(len(buf) - 6):
        r = buf[i:i + 7]
        if r[0] == 0x90 and r[1] == 0x50 and all(b <= 0x0F for b in r[2:6]) and r[6] == 0xFF:
            return True
    return False
for baud in (9600, 38400, 115200):
    try:
        with serial.Serial(port, baud, timeout=0.05) as s:
            s.reset_input_buffer()
            ok = 0
            for _ in range(2):
                s.write(INQ + PADS)
                buf, end = b"", time.monotonic() + 0.8
                while time.monotonic() < end and not zoom_reply(buf):
                    buf += s.read(64)
                ok += zoom_reply(buf)
            if ok == 2:
                print(baud)
                sys.exit(0)
    except Exception:
        pass
sys.exit(1)
PY
  then visca="$port"; break; fi
done

rules="$(mktemp)"
cat > "$rules" <<'HDR'
# Generated by fcb_udev_setup.sh -- stable names for the Sony FCB-EV9520L.
SUBSYSTEM=="video4linux", ATTR{name}=="*NeoHD*", ATTR{index}=="0", SYMLINK+="fcb_video"
SUBSYSTEM=="video4linux", ATTR{name}=="*FCB*", ATTR{index}=="0", SYMLINK+="fcb_video"
SUBSYSTEM=="video4linux", ATTR{name}=="*Harrier*", ATTR{index}=="0", SYMLINK+="fcb_video"
# Known boards by USB ID, for card names that say nothing ("FX3 CAMERA" on Oppila's).
SUBSYSTEM=="video4linux", ATTRS{idVendor}=="04b4", ATTRS{idProduct}=="00f[89]", ATTR{index}=="0", SYMLINK+="fcb_video"
SUBSYSTEM=="video4linux", ATTRS{idVendor}=="04b4", ATTRS{idProduct}=="0040", ATTR{index}=="0", SYMLINK+="fcb_video"
HDR
if [[ -n "$visca" ]]; then
  vid=$(udevadm info -q property -n "$visca" | sed -n 's/^ID_VENDOR_ID=//p')
  pid=$(udevadm info -q property -n "$visca" | sed -n 's/^ID_MODEL_ID=//p')
  serial=$(udevadm info -q property -n "$visca" | sed -n 's/^ID_SERIAL_SHORT=//p')
  echo "visca port: $visca (usb $vid:$pid serial '${serial:-n/a}')"
  iface=$(udevadm info -q property -n "$visca" | sed -n 's/^ID_USB_INTERFACE_NUM=//p')
  line="SUBSYSTEM==\"tty\", ATTRS{idVendor}==\"$vid\", ATTRS{idProduct}==\"$pid\""
  [[ -n "$serial" ]] && line+=", ATTRS{serial}==\"$serial\""
  # Pinned to the interface: the Oppila board has a second, debug, ACM port
  # under the same USB ID, which would otherwise take the symlink too.
  [[ -n "$iface" ]] && line+=", ENV{ID_USB_INTERFACE_NUM}==\"$iface\""
  line+=", SYMLINK+=\"fcb_visca\", MODE=\"0666\""
  echo "$line" >> "$rules"
  echo "SUBSYSTEM==\"usb\", ATTR{idVendor}==\"$vid\", ATTR{idProduct}==\"$pid\", MODE=\"0664\", GROUP=\"plugdev\"" >> "$rules"
else
  echo "warning: no serial port answered VISCA; rule for /dev/fcb_visca not generated" >&2
fi

echo "---- rules ----"; cat "$rules"; echo "---------------"
if [[ $DRY == 1 ]]; then rm -f "$rules"; exit 0; fi
sudo install -m 0644 "$rules" /etc/udev/rules.d/99-fcb-camera.rules
sudo udevadm control --reload
sudo udevadm trigger
rm -f "$rules"
sleep 1
ls -l /dev/fcb_video /dev/fcb_visca 2>/dev/null || echo "symlinks will appear after replugging the camera"
